export interface GoodLook {
  shape: string;
  b: string;
  a?: string;
  s?: string;
  d?: string;
  l?: string;
  o?: string;
}

const g = (
  shape: string,
  b: string,
  extra: Omit<GoodLook, "shape" | "b"> = {},
): GoodLook => ({ shape, b, ...extra });

