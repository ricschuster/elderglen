/** The ice fishing prize, drawn on the slim fish body (note 82). */
export const FROSTFIN_LOOK = {
  d: "#4a6a9a",
  b: "#a8d0f0",
  l: "#f4faff",
  f: "#7ab4e8",
  m: "#e8f6ff",
};

export const goodKey = (id: string) => `icon-good-${id}`;

function paletteOf(k: GoodLook): Record<string, string> {
  return {
    o: k.o ?? darken(k.b, 0.6),
    b: k.b,
    d: k.d ?? darken(k.b, 0.3),
    l: k.l ?? mix(k.b, "#ffffff", 0.45),
    a: k.a ?? darken(k.b, 0.2),
    s: k.s ?? darken(k.b, 0.45),
  };
}

function paintRows(
  scene: Phaser.Scene,
  key: string,
  rows: string[],
  colour: (ch: string) => string | undefined,
) {
  const top = Math.floor((SIZE - rows.length) / 2) + 1;
  const t = scene.textures.createCanvas(key, SIZE, SIZE)!;
  const c = t.getContext();
  c.fillStyle = "#00000030";
  c.fillRect(3, SIZE - 2, 10, 1);
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const col = colour(row[x]!);
      if (!col) continue;
      c.fillStyle = col;
      c.fillRect(x, top + y, 1, 1);
    }
  });
  t.refresh();
}

/** Paint every good in `GOOD_LOOKS`, and the Frostfin. */
export function paintGoods(scene: Phaser.Scene): void {
  for (const [id, k] of Object.entries(GOOD_LOOKS)) {
    const p = paletteOf(k);
    paintRows(scene, goodKey(id), GOOD_SHAPES[k.shape]!, (ch) => p[ch]);
  }
  paintRows(scene, goodKey("frostfin"), FISH_SHAPES.slim, (ch) =>
    colourOf(ch, FROSTFIN_LOOK),
  );
}
